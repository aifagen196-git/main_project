drop policy if exists "active_jobs_read" on public.jobs;
create policy "active_jobs_read" on public.jobs for select
  to anon, authenticated
  using (is_active and (expires_at is null or expires_at > now()));

drop policy if exists "resumes_select_own" on public.resumes;
create policy "resumes_select_own" on public.resumes for select
  to authenticated using (auth.uid() = user_id);
drop policy if exists "resumes_insert_own" on public.resumes;
create policy "resumes_insert_own" on public.resumes for insert
  to authenticated with check (auth.uid() = user_id);
drop policy if exists "resumes_update_own" on public.resumes;
create policy "resumes_update_own" on public.resumes for update
  to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists "resumes_delete_own" on public.resumes;
create policy "resumes_delete_own" on public.resumes for delete
  to authenticated using (auth.uid() = user_id);

drop policy if exists "preferences_own" on public.user_job_preferences;
create policy "preferences_own" on public.user_job_preferences for all
  to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);

insert into storage.buckets (id, name, public)
values ('resumes', 'resumes', false)
on conflict (id) do update set public = false;

drop policy if exists "resume_objects_select_own" on storage.objects;
create policy "resume_objects_select_own" on storage.objects for select
  to authenticated
  using (bucket_id = 'resumes' and (storage.foldername(name))[1] = auth.uid()::text);
drop policy if exists "resume_objects_insert_own" on storage.objects;
create policy "resume_objects_insert_own" on storage.objects for insert
  to authenticated
  with check (bucket_id = 'resumes' and (storage.foldername(name))[1] = auth.uid()::text);
drop policy if exists "resume_objects_update_own" on storage.objects;
create policy "resume_objects_update_own" on storage.objects for update
  to authenticated
  using (bucket_id = 'resumes' and (storage.foldername(name))[1] = auth.uid()::text)
  with check (bucket_id = 'resumes' and (storage.foldername(name))[1] = auth.uid()::text);
drop policy if exists "resume_objects_delete_own" on storage.objects;
create policy "resume_objects_delete_own" on storage.objects for delete
  to authenticated
  using (bucket_id = 'resumes' and (storage.foldername(name))[1] = auth.uid()::text);
